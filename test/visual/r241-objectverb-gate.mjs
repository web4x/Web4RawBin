// T24.1 — objectVerb introspection engine gate. Verifies the Chain CLI commands work
// correctly + deterministically: scoreboard / followUp / lintMarkers / emitClaudeSkills.
// Impl 5453f58d (ObjectVerbEngine.introspect, scripts/objectVerb.ts). DET-3x.
// emitClaudeSkills is gated via the pure emitClaudeSkillText('Chain') (no real-file mutation).

import { execSync } from 'child_process';

const REPO = '/var/dev/Workspaces/2cuGitHub/Web4RawBin';
const run = (cmd) => { try { return execSync(cmd, { cwd: REPO, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 60000 }); } catch (e) { return (e.stdout || '') + (e.stderr || ''); } };
const OV = 'npx tsx scripts/objectVerb.ts';

const results = [];
let prev = null;
for (let r = 1; r <= 3; r++) {
  // (a) scoreboard -> canonical "## Summary: N/M COMPLETE"
  const sb = run(`${OV} chain scoreboard`);
  const sbM = sb.match(/## Summary: (\d+)\/(\d+) COMPLETE/);
  const scoreboardOk = !!sbM;

  // (b) followUp -> produces rows / complete-total (the canonical completion measure)
  const fu = run(`${OV} chain followUp`);
  const followUpOk = /"?(complete|total)"?\s*[:=]\s*\d+/i.test(fu) || /\|\s*R\d/.test(fu) || fu.includes('COMPLETE');

  // (c) lintMarkers -> runs, emits findings (prefix-collision / shared-impl / orphan lines or a clean signal)
  const lm = run(`${OV} chain lintMarkers`);
  const lintLines = lm.split('\n').filter(l => l.trim()).length;
  const lintOk = lintLines > 0 && !/Error:|Cannot find|is not a function/i.test(lm);

  // (d) emitClaudeSkills via the pure text builder (deterministic, no write)
  const skill = run(`npx tsx -e "import {emitClaudeSkillText} from './scripts/objectVerb.ts'; process.stdout.write(emitClaudeSkillText('Chain'))"`);
  const emitOk = skill.length > 500 && /GENERATED by/.test(skill) && /Chain/.test(skill);

  const snap = { score: sbM ? `${sbM[1]}/${sbM[2]}` : null, lintLines, skillLen: skill.length };
  const deterministic = !prev || (prev.score === snap.score && prev.lintLines === snap.lintLines && prev.skillLen === snap.skillLen);
  prev = snap;

  const pass = scoreboardOk && followUpOk && lintOk && emitOk && deterministic;
  results.push(pass);
  console.log(`run ${r}: scoreboard=${scoreboardOk}(${snap.score}) followUp=${followUpOk} lintMarkers=${lintOk}(${lintLines} lines) emitSkills=${emitOk}(${skill.length}c) det=${deterministic} => ${pass ? 'GREEN' : 'RED'}`);
}

console.log('\n=== VERDICT objectVerb engine (DET-3x) ===');
results.forEach((p, i) => console.log(`  run ${i + 1}: ${p ? 'GREEN' : 'RED'}`));
const green = results.length === 3 && results.every(Boolean);
console.log('OVERALL:', green ? 'GREEN DET-3x' : 'RED');
process.exit(green ? 0 : 1);
