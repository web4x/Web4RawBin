describe('emitOosh generates canonical OOSH (oosh-po rules)', () => {
  const text = emitOoshText('taskChain');

  it('ends with scriptname.start "$@" (canonical dispatch, not .bootstrap)', () => {
    expect(text.trimEnd().endsWith('taskChain.start "$@"')).toBe(true);
    expect(text).not.toContain('bootstrap');
  });

  it('uses two-hash signature comments and per-method completion helpers', () => {
    expect(text).toMatch(/taskChain\.chain\.followUp\(\) # <reqUuids> <\?sprint> # /);
    expect(text).toContain('taskChain.chain.followUp.completion.sprint()');
    expect(text).toContain('taskChain.chain.wireImplNode.completion.methodUuid()');
  });

  it('prefixes the dispatch helper with private. and forbids flags', () => {
    expect(text).toContain('private.taskChain.dispatch()');
    expect(text).not.toMatch(/\) # -[a-z-]+ #/); // no flag-style params in signatures
  });
});

