describe('objectVerb introspection (c2 for TypeScript)', () => {
  const sigs = introspect();
  const verb = (o: string, v: string) => sigs.find(s => s.object === o && s.verb === v);

  it('finds all Chain verbs incl. resolvePrefix (lazy-JSDoc regression guard)', () => {
    for (const v of ['resolvePrefix', 'followUp', 'listComplete', 'scoreboard', 'wireImplNode', 'wireAllMissing', 'generateMatrix', 'updateMatrixRow', 'complete']) {
      expect(verb('Chain', v), `Chain.${v}`).toBeTruthy();
    }
    expect(verb('Velocity', 'dashboard')).toBeTruthy();
    expect(verb('Velocity', 'compute')).toBeTruthy();
  });

  it('excludes private methods and constructor', () => {
    expect(sigs.find(s => s.verb === 'constructor')).toBeUndefined();
    expect(sigs.find(s => s.verb === 'walkReq')).toBeUndefined();
    expect(sigs.find(s => s.verb === 'markerScanners')).toBeUndefined();
    expect(sigs.find(s => s.verb === 'summarize')).toBeUndefined();
  });

  it('parses params with types and optionality', () => {
    const f = verb('Chain', 'followUp')!;
    expect(f.params).toEqual([
      { name: 'reqUuids', type: 'string[]', optional: false },
      { name: 'sprint', type: 'string', optional: true },
    ]);
    const d = verb('Velocity', 'dashboard')!;
    expect(d.params.map(p => p.name)).toEqual(['since', 'hours', 'sprint']);
    expect(d.params.every(p => p.optional)).toBe(true);
    expect(d.params[1].type).toBe('number');
  });

  it('binds JSDoc first line as the doc', () => {
    expect(verb('Chain', 'listComplete')!.doc).toMatch(/COMPLETE chain set/);
  });
});

describe('objectVerb arg mapping', () => {
  const sig: VerbSig = {
    object: 'X', verb: 'v',
    params: [
      { name: 'ids', type: 'string[]', optional: false },
      { name: 'sprint', type: 'string', optional: true },
      { name: 'dryRun', type: 'boolean', optional: true },
      { name: 'hours', type: 'number', optional: true },
    ],
    doc: '',
  };

  it('maps positionals to string[], named --params by name', () => {
    expect(mapArgs(sig, ['a', 'b', '--sprint', 'S19'])).toEqual([['a', 'b'], 'S19', undefined, undefined]);
  });

  it('maps boolean flags by presence and numbers by parse', () => {
    expect(mapArgs(sig, ['--dryRun', '--hours', '5'])).toEqual([[], undefined, true, 5]);
  });
});

